"""mksizes.py: write fnsizes.h, every game function's address and size (from functions.csv), sorted by address.
recomp.c uses it before hooking a function to compare the function's bytes in memory with the exe on disk: the
patch DLL rewrites some functions (call sites, entries) at start-up, and a rebuild of the code on disk would undo
that. Run again if functions.csv changes."""
import csv, os
here = os.path.dirname(os.path.abspath(__file__))
src = os.path.join(here, '..', '..', 'decomp', 'out', 'functions.csv')
rows = sorted((int(r[0], 16), int(r[2])) for r in csv.reader(open(src)) if r[0] != 'address')
with open(os.path.join(here, '..', 'fnsizes.h'), 'w', newline='\r\n') as f:
    f.write('/* generated by tools/mksizes.py from decomp/out/functions.csv: { address, size } */\n')
    f.write('static const DWORD g_fnSizes[][2] = {\n')
    for i in range(0, len(rows), 6):
        f.write('\t' + ' '.join('{ 0x%06x, %d },' % r for r in rows[i:i + 6]) + '\n')
    f.write('};\n')
print(len(rows), 'functions')
