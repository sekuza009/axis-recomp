"""mkscene.py: src/scene.fields -> src/scene.h, the scene object as a packed C struct. Fields are sorted by offset,
the gaps become _padXXXXXXX arrays, overlaps are errors, and every field's offset and size are checked at compile
time (_Static_assert), so a wrong entry cannot build."""
import os, re
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
SIZE = 0x2343b0b
rows = []
for n, line in enumerate(open(os.path.join(here, 'scene.fields'))):
    line = line.rstrip('\n')
    if not line.strip() or line.lstrip().startswith('#'): continue
    body, _, comment = line.partition('#')
    m = re.match(r'\s*(0x[0-9a-fA-F]+|\d+)\s+(0x[0-9a-fA-F]+|\d+)\s+(.+?)\s*$', body)
    if not m: raise SystemExit('scene.fields line %d: %r' % (n + 1, line))
    decl = m.group(3).rstrip(';')
    name = re.match(r'.*?(\w+)\s*(\[.*\])?$', decl).group(1)
    rows.append((int(m.group(1), 0), int(m.group(2), 0), decl, name, comment.strip()))
rows.sort()
out = ['/* scene.h: generated by tools/mkscene.py from scene.fields - edit that file, not this one */',
       '#ifndef SCENE_H', '#define SCENE_H', '#include "axis.h"', '',
       '/* a message waiting in the box (msgRing) */',
       '#pragma pack(push, 1)',
       'typedef struct { u32 unk0; u32 text; i32 colour; u32 unk12; u32 unk16; } MessageSlot;   /* colour: index into g_textColours, 16 and up: none */',
       '/* one line of the event list (events) */',
       'typedef struct { u32 type; char text[0x104]; } EventLine;   /* type 0..5: the colour */',
       '', 'typedef struct Scene {']
pos = 0
for off, size, decl, name, comment in rows:
    if off < pos: raise SystemExit('field %s at %#x overlaps the one before (ends at %#x)' % (name, off, pos))
    if off > pos: out.append('\tu8 _pad%07x[0x%x];' % (pos, off - pos))
    out.append('\t%s;%s' % (decl, ('   /* +0x%x: %s */' % (off, comment)) if comment else '   /* +0x%x */' % off))
    pos = off + size
if pos < SIZE: out.append('\tu8 _pad%07x[0x%x];' % (pos, SIZE - pos))
out += ['} Scene;', '#pragma pack(pop)', '']
for off, size, decl, name, comment in rows:
    out.append('_Static_assert(offsetof(Scene, %s) == 0x%x && sizeof(((Scene *)0)->%s) == 0x%x, "scene.fields: %s");' % (name, off, name, size, name))
out += ['_Static_assert(sizeof(Scene) == 0x%x, "scene size");' % SIZE, '', '#endif', '']
open(os.path.join(here, 'scene.h'), 'w', newline='\n').write('\n'.join(out))
print('scene.h: %d fields' % len(rows))
