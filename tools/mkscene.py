"""mkscene.py: src/scene.fields -> src/scene.h: the game's record types and the scene object as packed C structs.
scene.fields holds sections "struct Name size" .. fields .. (one field per line: offset  size  declaration  # comment);
types used by later sections come first. Fields are sorted by offset, the gaps become _padXXXXXXX arrays, overlaps
are errors, and every field's offset and size is checked at compile time (_Static_assert). A field may be an
anonymous union of views of the same bytes ("union { float puffWait; float markPoints[3][3]; }"): each member is checked
at the offset, none larger than the size."""
import os, re
here = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'src')
structs = []; cur = None
for n, line in enumerate(open(os.path.join(here, 'scene.fields'))):
    line = line.rstrip('\n')
    if not line.strip() or line.lstrip().startswith('#'): continue
    body, _, comment = line.partition('#')
    m = re.match(r'\s*struct\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*$', body)
    if m:
        cur = (m.group(1), int(m.group(2), 0), comment.strip(), []); structs.append(cur); continue
    m = re.match(r'\s*(0x[0-9a-fA-F]+|\d+)\s+(0x[0-9a-fA-F]+|\d+)\s+(.+?)\s*$', body)
    if not m or cur is None: raise SystemExit('scene.fields line %d: %r' % (n + 1, line))
    decl = m.group(3).rstrip(';')
    u = re.match(r'union\s*\{(.*)\}$', decl)
    if u:   # (an anonymous union: its members' names)
        name = [re.match(r'.*?(\w+)\s*(\[.*\])?$', d.strip()).group(1) for d in u.group(1).split(';') if d.strip()]
    else:
        name = re.match(r'.*?(\w+)\s*(\[.*\])?$', decl).group(1)
    cur[3].append((int(m.group(1), 0), int(m.group(2), 0), decl, name, comment.strip()))
out = ['/* scene.h: generated by tools/mkscene.py from scene.fields - edit that file, not this one */',
       '#ifndef SCENE_H', '#define SCENE_H', '#include "axis.h"', '', '#pragma pack(push, 1)']
asserts = []
for sname, ssize, scomment, rows in structs:
    rows.sort()
    out += ['', '/* %s */' % scomment if scomment else '', 'typedef struct %s {' % sname]
    pos = 0
    for off, size, decl, name, comment in rows:
        if off < pos: raise SystemExit('%s.%s at %#x overlaps the field before (ends at %#x)' % (sname, name, off, pos))
        if off > pos: out.append('\tu8 _pad%07x[0x%x];' % (pos, off - pos))
        out.append('\t%s;%s' % (decl, ('   /* +0x%x: %s */' % (off, comment)) if comment else '   /* +0x%x */' % off))
        pos = off + size
    if pos > ssize: raise SystemExit('%s: fields run past its size' % sname)
    if pos < ssize: out.append('\tu8 _pad%07x[0x%x];' % (pos, ssize - pos))
    out.append('} %s;' % sname)
    for off, size, decl, name, comment in rows:
        if isinstance(name, list):
            for n_ in name:
                asserts.append('_Static_assert(offsetof(%s, %s) == 0x%x && sizeof(((%s *)0)->%s) <= 0x%x, "scene.fields: %s.%s");'
                               % (sname, n_, off, sname, n_, size, sname, n_))
            continue
        asserts.append('_Static_assert(offsetof(%s, %s) == 0x%x && sizeof(((%s *)0)->%s) == 0x%x, "scene.fields: %s.%s");'
                       % (sname, name, off, sname, name, size, sname, name))
    asserts.append('_Static_assert(sizeof(%s) == 0x%x, "scene.fields: size of %s");' % (sname, ssize, sname))
out += ['#pragma pack(pop)', ''] + asserts + ['', '#endif', '']
open(os.path.join(here, 'scene.h'), 'w', newline='\n').write('\n'.join(out))
print('scene.h: %s' % ', '.join('%s %d fields' % (s[0], len(s[3])) for s in structs))
