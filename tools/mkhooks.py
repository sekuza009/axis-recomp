"""mkhooks.py <out.c>: the standalone build's hook table, generated from recomp.c (its one source): every rebuilt
function the harness switches in (HIT_TESTS, g_hooks3 and install_hooks' own list), with its original address, and
the call-target bytes the patch DLL may rewrite inside a rebuilt function (g_patchOk). See standalone/main.c."""
import glob, re, struct, sys

t = open('recomp.c', encoding='utf-8-sig').read()
hooks = []
a = t.index('#define HIT_TESTS(X)'); b = t.index('\n', t.index('pilotSelect_hitTest', a))
hooks += [(int(x, 16), n) for x, n in re.findall(r'X\((0x[0-9a-f]+), 0x[0-9a-f]+, 0x[0-9a-f]+, (\w+)\)', t[a:b])]
a = t.index('g_hooks3[] = {'); b = t.index('\n};', a)
for x, fn, n in re.findall(r'\{ (0x[0-9a-f]+), \(void \*\)(\w+), "(\w+)" \}', t[a:b]):
	assert fn == n, n
	hooks.append((int(x, 16), n))
a = t.index('static void install_hooks(int state_ok)'); b = t.index('\n}\n', a)
for x, fn, n in re.findall(r'\thook\((0x[0-9a-f]+), \(void \*\)(\w+), "(\w+)"\);', t[a:b]):
	assert fn == n, n
	hooks.append((int(x, 16), n))
assert len({x for x, _ in hooks}) == len(hooks) and len({n for _, n in hooks}) == len(hooks), 'duplicate hook'
# the compiler's jump stubs ("jmp <a rebuilt function>") that the game's data points at (the static constructor table
# 0x4ad000 has 30 of them): entries of the same rebuilt function, so the loader puts its own jump there
b = open('installed.exe', 'rb').read()
pe = struct.unpack_from('<I', b, 0x3c)[0]; nsec = struct.unpack_from('<H', b, pe + 6)[0]; opt = struct.unpack_from('<H', b, pe + 20)[0]
secs = {}
for i in range(nsec):
	nm, vs, va, rs, rp = struct.unpack_from('<8sIIII', b, pe + 24 + opt + 40 * i)
	secs[nm.rstrip(b'\0')] = (0x400000 + va, vs, rs, rp)
tbase, tvs, trs, trp = secs[b'.text']
by_addr = dict(hooks)
stubs = []
for name in (b'.rdata', b'.data'):
	base, vs, rs, rp = secs[name]
	for o in range(0, min(rs, vs) - 3, 4):
		v = struct.unpack_from('<I', b, rp + o)[0]
		if tbase <= v < tbase + tvs - 5 and v not in by_addr and b[trp + v - tbase] == 0xE9:
			to = v + 5 + struct.unpack_from('<i', b, trp + v - tbase + 1)[0]
			if to in by_addr and (v, by_addr[to]) not in stubs:
				stubs.append((v, by_addr[to]))
a = t.index('static const DWORD g_patchOk[][2] = {'); b = t.index('\n};', a)
patch_ok = t[t.index('{', a + 30) + 1:b].strip('\n')

# each rebuild's linker symbol, from the objects build.sh made (stdcall ones are decorated _name@bytes)
def coff_symbols(path):
	d = open(path, 'rb').read()
	symptr, nsyms = struct.unpack_from('<II', d, 8)
	strtab = symptr + nsyms * 18
	i = 0
	while i < nsyms:
		e = d[symptr + i * 18:symptr + i * 18 + 18]
		raw, _, secnum, _, sclass, naux = struct.unpack('<8sIhHBB', e)
		if raw[:4] == b'\0\0\0\0':
			off = struct.unpack_from('<I', raw, 4)[0]
			name = d[strtab + off:d.index(b'\0', strtab + off)]
		else:
			name = raw.rstrip(b'\0')
		if secnum > 0 and sclass == 2:
			yield name.decode()
		i += 1 + naux
syms = {}
for o in glob.glob('build/obj/*.o'):
	for s in coff_symbols(o):
		syms.setdefault(re.sub(r'@\d+$', '', s[1:] if s.startswith('_') else s), s)
missing = [n for _, n in hooks if n not in syms]
if missing:
	sys.exit('not defined in src (build/obj): ' + ', '.join(missing))

# the game's code bytes the rebuilds read (call sites they follow live, patched operands, code_matches): every
# address in src/ inside the game's own code that is not a rebuilt function's entry, with 16 bytes either side
# (for AXISRC_POISON, see standalone/main.c)
entries = {x for x, _ in hooks}
lits = set()
for f in glob.glob('src/**/*.[ch]', recursive=True):
	for m in re.findall(r'0x(4[0-9a-f]{5})\b', open(f, encoding='latin-1').read()):
		a = int(m, 16)
		if (0x401000 <= a < 0x49e000 or 0x4a8300 <= a < 0x4a8740 or 0x4a8e20 <= a < 0x4a9000) and a not in entries:
			lits.add(a)
keep = []
for a in sorted(lits):
	lo, hi = a - 16, a + 16
	if keep and lo <= keep[-1][1]: keep[-1][1] = max(keep[-1][1], hi)
	else: keep.append([lo, hi])

out = ['/* generated by tools/mkhooks.py from recomp.c: do not edit */',
       '#include "standalone.h"', '']
out += ['extern char %s[] __asm__("%s");' % (n, syms[n]) for _, n in sorted(hooks, key=lambda h: h[1])]
out += ['', 'const unsigned g_saKeep[][2] = {'] + ['\t{ 0x%06x, 0x%06x },' % (lo, hi) for lo, hi in keep] + ['};',
        'const int g_saNkeep = sizeof g_saKeep / sizeof g_saKeep[0];']
out += ['', 'const SaHook g_saHooks[] = {']
out += ['\t{ 0x%06x, (void *)%s, "%s" },' % (x, n, n) for x, n in sorted(hooks)]
out += ['	{ 0x%06x, (void *)%s, "%s (jump stub)" },' % (x, n, n) for x, n in sorted(stubs)]
out += ['};', 'const int g_saNhooks = sizeof g_saHooks / sizeof g_saHooks[0];', '',
        'const unsigned g_saPatchOk[][2] = {', patch_ok, '};',
        'const int g_saNpatchOk = sizeof g_saPatchOk / sizeof g_saPatchOk[0];', '']
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out))
print('%d hooks, %d patch-ok ranges' % (len(hooks), patch_ok.count('{')))
