r"""gen.py out.c: the range-trace walker for AxisRC: every field of scene.fields (by offset, for each instance
reachable from the scene, the globals and the objects), every global of globals.h and every object of objects.h
becomes a leaf; rtrace.c samples them all and keeps per-leaf statistics."""
import re, sys
R = 'C:/Users/Alexander/Desktop/Axis/recomp/src/'

SCALAR = {'i32': ('i', 4), 'int': ('i', 4), 'signed int': ('i', 4), 'long': ('i', 4), 'u32': ('u', 4),
          'unsigned': ('u', 4), 'unsigned int': ('u', 4), 'DWORD': ('u', 4), 'BOOL': ('i', 4),
          'float': ('f', 4), 'double': ('d', 8), 'u8': ('B', 1), 'unsigned char': ('B', 1), 'BYTE': ('B', 1),
          'signed char': ('b', 1), 'i8': ('b', 1), 'char': ('c', 1), 'u16': ('w', 2), 'unsigned short': ('w', 2),
          'short': ('h', 2), 'i16': ('h', 2), 'signed short': ('h', 2), 'u64': ('q', 8), 'int64_t': ('q', 8),
          'i64': ('q', 8), 'LONGLONG': ('q', 8)}


def parse_fields():
    structs, cur = {}, None
    for line in open(R + 'scene.fields', encoding='latin-1'):
        line = line.rstrip('\r\n')
        m = re.match(r'struct (\w+) (0x[0-9a-f]+|\d+)', line)
        if m:
            cur = m.group(1)
            structs[cur] = dict(size=int(m.group(2), 0), fields=[])
            continue
        m = re.match(r'^(0x[0-9a-f]+|\d+)\s+(0x[0-9a-f]+|\d+)\s+(.*?)\s*(#.*)?$', line)
        if not (m and cur):
            continue
        off, size, decl = int(m.group(1), 0), int(m.group(2), 0), m.group(3).strip().rstrip(';')
        if decl.startswith('union'):
            for mem in re.findall(r'([^;{}]+);', decl):
                structs[cur]['fields'].append((off, None, mem.strip()))
            continue
        structs[cur]['fields'].append((off, size, decl))
    return structs


def split_decl(decl):
    """'const float *markCoords' -> (type 'const float', ptr 1, name, dims [..])"""
    m = re.match(r'^(.*?)(\**)\s*(\w+)\s*((?:\[[^\]]+\])*)$', decl.replace('* ', '*').replace(' *', ' *'))
    if not m:
        return None
    t, name, dims = m.group(1).strip(), m.group(3), [int(eval(d)) for d in re.findall(r'\[([^\]]+)\]', m.group(4))]
    ptr = decl.count('*')
    t = t.replace('*', '').strip()
    t = re.sub(r'^(const|volatile|struct)\s+', '', t)
    t = re.sub(r'^(const|volatile|struct)\s+', '', t)
    return t, ptr, name, dims


structs = parse_fields()
leaves = []       # (name, kind, esz, strlen)
lid = {}


def leaf(name, kind, esz, slen=0):
    if name not in lid:
        lid[name] = len(leaves)
        leaves.append((name, kind, esz, slen))
    return lid[name]


skipped = []
walk = {}
for sname, s in structs.items():
    body = []
    for off, size, decl in s['fields']:
        d = split_decl(decl)
        if not d:
            skipped.append('%s: %s' % (sname, decl)); continue
        t, ptr, name, dims = d
        n = 1
        for x in dims:
            n *= x
        full = '%s.%s' % (sname, name)
        if ptr:
            body.append('\trt_O(%d, p + 0x%x, %d, 4);' % (leaf(full, 'p', 4), off, n)); continue
        if t == 'Colour':
            body.append('\trt_O(%d, p + 0x%x, %d, 4);' % (leaf(full, 'f', 4), off, n * 4)); continue
        if t in SCALAR:
            k, esz = SCALAR[t]
            if k == 'c' and dims:
                sl = dims[-1]
                body.append('\trt_S(%d, p + 0x%x, %d, %d);' % (leaf(full, 's', 1, sl), off, n // sl, sl)); continue
            if size and esz * n != size and not (size % (esz * n) == 0):
                skipped.append('%s.%s size %x != %d x %d' % (sname, name, size, n, esz))
            cap = min(n, 4096)
            body.append('\trt_O(%d, p + 0x%x, %d, %d);' % (leaf(full, k, esz), off, cap, esz)); continue
        if t in structs:
            sz = structs[t]['size']
            cap = min(n, 20000)
            body.append('\tfor (int i = 0; i < %d; i++) w_%s(p + 0x%x + i * 0x%x);' % (cap, t, off, sz)); continue
        skipped.append('%s.%s: type %s' % (sname, name, t))
    walk[sname] = body

out = ['/* generated by gen.py */', '#include "game.h"', '#include "rtrace.h"', 'int rt_copy(const void *a, void *b, unsigned n);', 'const rt_u8 *rt_scene(void) { return (const rt_u8 *)g_scene; }']
for sname in structs:
    out.append('static void w_%s(const u8 *p);' % sname)
for sname, body in walk.items():
    out.append('static void w_%s(const u8 *p)\n{' % sname)
    out += body
    out.append('}')

# ---- globals
gl = []
for line in open(R + 'globals.h', encoding='latin-1'):
    m = re.match(r'#define (\w+) GAME_VAR\(([^,]+),\s*(0x[0-9a-f]+)\)', line)
    if not m:
        continue
    name, t = m.group(1), m.group(2).strip()
    tt = re.sub(r'^(const|volatile|struct)\s+', '', t)
    if '*' in t:
        base = tt.replace('*', '').strip()
        gl.append('\trt_O(%d, (const u8 *)&%s, 1, 4);' % (leaf(name, 'p', 4), name))
        if base in structs and t.count('*') == 1:
            gl.append('\tROOT(%s, %s, 0x%x);' % (name, base, structs[base]['size']))
        continue
    if tt in SCALAR:
        k, esz = SCALAR[tt]
        gl.append('\trt_O(%d, (const u8 *)&%s, 1, %d);' % (leaf(name, k, esz), name, esz))
    elif tt in structs:
        gl.append('\tw_%s((const u8 *)&%s);' % (tt, name))
    else:
        skipped.append('global %s: type %s' % (name, t))
# ---- objects
for line in open(R + 'objects.h', encoding='latin-1'):
    m = re.match(r'#define (\w+) \(\((?:struct )?([\w ]+?)\s*\*\)IMG\((0x[0-9a-f]+)\)\)\s*/\*\s*([\w ]+?)\[(\w+)\]', line)
    if not m:
        if line.startswith('#define'):
            skipped.append('object line: ' + line[:90].strip())
        continue
    name, t, n = m.group(1), m.group(2).strip(), int(eval(m.group(5)))
    if t in structs:
        gl.append('\tfor (int i = 0; i < %d; i++) w_%s((const u8 *)%s + i * 0x%x);' % (n, t, name, structs[t]['size']))
    elif t == 'Colour':
        gl.append('\trt_O(%d, (const u8 *)%s, %d, 4);' % (leaf(name, 'f', 4), name, n * 4))
    elif t == 'char':
        gl.append('\trt_S(%d, (const u8 *)%s, 1, %d);' % (leaf(name, 's', 1, n), name, n))
    elif t in ('u8', 'unsigned char'):
        gl.append('\trt_O(%d, (const u8 *)%s, %d, 1);' % (leaf(name, 'B', 1), name, min(n, 4096)))
    elif t in SCALAR:
        k, esz = SCALAR[t]
        gl.append('\trt_O(%d, (const u8 *)%s, %d, %d);' % (leaf(name, k, esz), name, min(n, 4096), esz))
    else:
        skipped.append('object %s: type %s' % (name, t))
out.append('void rt_walk_static(void)\n{')
out += gl
out.append('}')
out.append('''void rt_walk_textures(void)
{
	TextureManager *m = g_textures;
	if (!m) return;
	TextureManager c;
	if (!rt_copy(m, &c, sizeof c)) return;
	for (int i = 0; i < 6; i++) if (c.banks[i]) rt_root((const u8 *)c.banks[i], %d, 0x%x);
}''' % (list(structs).index('TextureBank'), structs['TextureBank']['size']))
out.append('void rt_walk_scene(const u8 *sc)\n{\n\tw_Scene(sc);\n\tw_Stage(sc + 0x1f36c8);\n}')
out.append('void rt_walk_any(int t, const u8 *p)\n{\n\tswitch (t) {')
for i, sname in enumerate(structs):
    out.append('\tcase %d: w_%s(p); break;' % (i, sname))
out.append('\t}\n}')
out.append('const char *const rt_structNames[] = {%s};' % ', '.join('"%s"' % s for s in structs))
out.append('const int rt_structCount = %d;' % len(structs))
out.append('Leaf rt_leaves[] = {')
for name, k, esz, sl in leaves:
    out.append('\t{"%s", \'%s\', %d, %d},' % (name, k, esz, sl))
out.append('};\nconst int rt_leafCount = %d;' % len(leaves))
src = '\n'.join(out) + '\n'
# ROOT(name, T, size): T's index for rt_walk_any
idx = {s: i for i, s in enumerate(structs)}
src = re.sub(r'ROOT\((\w+), (\w+), (0x[0-9a-f]+)\)', lambda m: 'rt_root((const u8 *)%s, %d, %s)' % (m.group(1), idx[m.group(2)], m.group(3)), src)
open(sys.argv[1], 'w').write(src)
print(len(leaves), 'leaves;', len(skipped), 'skipped')
for s in skipped:
    print('  skip', s)
