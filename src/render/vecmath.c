/* vecmath.c: the game's vector and 4x4 matrix helpers (Vec3, Vec4, Mat4: column-major), the segment-sphere test,
   the HSV colour conversion, the level table and two 4-value setters. These were the first functions rebuilt (they
   lived in the harness, recomp.c, until the standalone build needed them here).

   Float operands are taken from memory where the original's "fld a; fop [b]" does that (fld_m, fmul_m... in
   axis.h): a signalling NaN in memory meeting a quiet NaN on the stack gives the quiet one, which loading both
   first would not. Values the original only copies are copied as bits (BITS), never through the FPU. */
#include "../game.h"

typedef long double X;

#define COS_TABLE (g_cosTable)    /* 3600 entries, 1/10 degree */
#define SIN_TABLE (g_sinTable)
#define LD(p) fld_m(&(p))


/* 0x4722c0 Vec3::set(x, y, z), returns this */
float *THISCALL (Vec3_set)(float *v, float x, float y, float z)
{
	BITS(v[0]) = BITS(x); BITS(v[1]) = BITS(y); BITS(v[2]) = BITS(z);
	return v;
}

/* 0x467760 Vec3::normalize(), returns the length unrounded in ST0; a near-zero (or NaN) vector becomes (1, 0, 0)
   (the original's fcomp/test ah,1 is also true for NaN) */
X THISCALL (Vec3_normalize)(float *v)
{
	X len = x87_fsqrt((X)v[0] * v[0] + (X)v[1] * v[1] + (X)v[2] * v[2]);
	if (!(len >= 1e-8f)) {
		v[0] = 1.0f; v[1] = 0.0f; v[2] = 0.0f;
		return len;
	}
	v[0] = (float)(v[0] / len);
	v[1] = (float)(v[1] / len);
	v[2] = (float)(v[2] / len);
	return len;
}

/* 0x480250 Vec3::cross(out, b): out = this x b; the products stay in extended precision until the subtraction */
void THISCALL (Vec3_cross)(const float *a, float *out, const float *b)
{
	float x = f32(fmul_m(LD(a[1]), &b[2]) - fmul_m(LD(b[1]), &a[2]));
	float y = f32(fmul_m(LD(a[2]), &b[0]) - fmul_m(LD(a[0]), &b[2]));
	float z = f32(fmul_m(LD(b[1]), &a[0]) - fmul_m(LD(a[1]), &b[0]));
	out[0] = x; out[1] = y; out[2] = z;
}

/* 0x4802b0 Vec3::dot(b) */
float THISCALL (Vec3_dot)(const float *a, const float *b)
{
	return f32((X)b[0] * a[0] + (X)b[1] * a[1] + (X)b[2] * a[2]);
}

/* 0x4802d0 Vec3::add(out, b): out = b + this */
void THISCALL (Vec3_add)(const float *a, float *out, const float *b)
{
	float x = f32(fadd_m(LD(b[0]), &a[0])), y = f32(fadd_m(LD(b[1]), &a[1])), z = f32(fadd_m(LD(b[2]), &a[2]));
	out[0] = x; out[1] = y; out[2] = z;
}

/* 0x480320 Vec3::sub(out, b): out = this - b */
void THISCALL (Vec3_sub)(const float *a, float *out, const float *b)
{
	float x = f32(fsub_m(LD(a[0]), &b[0])), y = f32(fsub_m(LD(a[1]), &b[1])), z = f32(fsub_m(LD(a[2]), &b[2]));
	out[0] = x; out[1] = y; out[2] = z;
}

/* 0x480370 Vec3::scale(out, s): out = this * s */
void THISCALL (Vec3_scale)(const float *a, float *out, float s)
{
	float x = f32((X)s * a[0]), y = f32((X)s * a[1]), z = f32((X)s * a[2]);
	out[0] = x; out[1] = y; out[2] = z;
}

/* 0x4809d0 Vec4::set(x, y, z, w) */
void THISCALL (Vec4_set)(float *v, float x, float y, float z, float w)
{
	BITS(v[0]) = BITS(x); BITS(v[1]) = BITS(y); BITS(v[2]) = BITS(z); BITS(v[3]) = BITS(w);
}

/* 0x4677c0 Vec3::rotateAxis(axis, angle): rotate about axis 0 (z: x,y), 1 (x: y,z), 2 (y: z,x) by angle/10 deg */
void THISCALL (Vec3_rotateAxis)(float *v, int axis, int angle)
{
	int i = (angle % 3600 + 3600) % 3600;
	X c = COS_TABLE[i], s = SIN_TABLE[i];
	float t;
	switch (axis) {
	case 0: t = v[1]; v[1] = (float)(s * v[0] + c * v[1]); v[0] = (float)(c * v[0] - s * t); break;
	case 1: t = v[2]; v[2] = (float)(c * v[2] + s * v[1]); v[1] = (float)(c * v[1] - s * t); break;
	case 2: t = v[0]; v[0] = (float)(s * v[2] + c * v[0]); v[2] = (float)(c * v[2] - s * t); break;
	}
}

/* 0x47d380 Mat4_multiply(out, a, b): out = a * b. Generated by tools/x87gen.py from 0x47d38c..0x47d594: the
   original's term order and memory operands, each entry stored at once (out may overlap a or b) */
void (Mat4_multiply)(float *out, const float *a, const float *b)
{
	out[0] = (float)((((fmul_m(LD(a[8]), &b[2]) + fmul_m(LD(a[4]), &b[1])) + fmul_m(LD(a[0]), &b[0])) + fmul_m(LD(b[3]), &a[12])));
	out[4] = (float)((((fmul_m(LD(a[8]), &b[6]) + fmul_m(LD(b[7]), &a[12])) + fmul_m(LD(a[4]), &b[5])) + fmul_m(LD(a[0]), &b[4])));
	out[8] = (float)((((fmul_m(LD(b[11]), &a[12]) + fmul_m(LD(a[4]), &b[9])) + fmul_m(LD(b[8]), &a[0])) + fmul_m(LD(a[8]), &b[10])));
	out[12] = (float)((((fmul_m(LD(a[8]), &b[14]) + fmul_m(LD(a[4]), &b[13])) + fmul_m(LD(a[12]), &b[15])) + fmul_m(LD(b[12]), &a[0])));
	out[1] = (float)((((fmul_m(LD(a[13]), &b[3]) + fmul_m(LD(a[5]), &b[1])) + fmul_m(LD(a[9]), &b[2])) + fmul_m(LD(a[1]), &b[0])));
	out[5] = (float)((((fmul_m(LD(b[5]), &a[5]) + fmul_m(LD(a[1]), &b[4])) + fmul_m(LD(b[7]), &a[13])) + fmul_m(LD(b[6]), &a[9])));
	out[9] = (float)((((fmul_m(LD(a[5]), &b[9]) + fmul_m(LD(b[11]), &a[13])) + fmul_m(LD(b[10]), &a[9])) + fmul_m(LD(a[1]), &b[8])));
	out[13] = (float)((((fmul_m(LD(a[1]), &b[12]) + fmul_m(LD(a[13]), &b[15])) + fmul_m(LD(a[9]), &b[14])) + fmul_m(LD(a[5]), &b[13])));
	out[2] = (float)((((fmul_m(LD(a[14]), &b[3]) + fmul_m(LD(a[6]), &b[1])) + fmul_m(LD(a[10]), &b[2])) + fmul_m(LD(a[2]), &b[0])));
	out[6] = (float)((((fmul_m(LD(b[5]), &a[6]) + fmul_m(LD(a[2]), &b[4])) + fmul_m(LD(b[7]), &a[14])) + fmul_m(LD(b[6]), &a[10])));
	out[10] = (float)((((fmul_m(LD(a[6]), &b[9]) + fmul_m(LD(b[11]), &a[14])) + fmul_m(LD(b[10]), &a[10])) + fmul_m(LD(a[2]), &b[8])));
	out[14] = (float)((((fmul_m(LD(a[2]), &b[12]) + fmul_m(LD(a[14]), &b[15])) + fmul_m(LD(a[10]), &b[14])) + fmul_m(LD(a[6]), &b[13])));
	out[3] = (float)((((fmul_m(LD(a[15]), &b[3]) + fmul_m(LD(a[7]), &b[1])) + fmul_m(LD(a[11]), &b[2])) + fmul_m(LD(a[3]), &b[0])));
	out[7] = (float)((((fmul_m(LD(b[5]), &a[7]) + fmul_m(LD(a[3]), &b[4])) + fmul_m(LD(b[7]), &a[15])) + fmul_m(LD(b[6]), &a[11])));
	out[11] = (float)((((fmul_m(LD(a[7]), &b[9]) + fmul_m(LD(b[11]), &a[15])) + fmul_m(LD(b[10]), &a[11])) + fmul_m(LD(a[3]), &b[8])));
	out[15] = (float)((((fmul_m(LD(a[3]), &b[12]) + fmul_m(LD(a[15]), &b[15])) + fmul_m(LD(a[11]), &b[14])) + fmul_m(LD(a[7]), &b[13])));
}

/* 0x484860 Mat4_transformPoint(out4, m, p3): out = m * (p, 1). Row 0 is ((m8 p2 + m4 p1) + m0 p0) + m12, rows 1-3
   ((m[8+r] p2 + m[r] p0) + m[4+r] p1) + m[12+r]; each "fld m; fmul p", and each row is stored before the next is
   computed (out may overlap p) */
void (Mat4_transformPoint)(float *out, const float *m, const float *p)
{
	out[0] = (float)fadd_m(fmul_m(LD(m[8]), &p[2]) + fmul_m(LD(m[4]), &p[1]) + fmul_m(LD(m[0]), &p[0]), &m[12]);
	for (int r = 1; r < 4; r++)
		out[r] = (float)fadd_m(fmul_m(LD(m[8 + r]), &p[2]) + fmul_m(LD(m[r]), &p[0]) + fmul_m(LD(m[4 + r]), &p[1]),
		                       &m[12 + r]);
}

/* 0x47d610 Mat4_minor(m, out3x3, row, col): the 3x3 matrix left after removing row and col (m[row*4+col]) */
void (Mat4_minor)(const float *m, float *out, int row, int col)
{
	int k = 0;
	for (int r = 0; r < 4; r++)
		for (int c = 0; c < 4; c++)
			if (r != row && c != col)
				((u32 *)out)[k++] = ((const u32 *)m)[r * 4 + c];
}

/* 3x3 determinant in the original's operation order and memory operands:
   ((n8 n4 - n7 n5) n0 - (n1 n8 - n2 n7) n3) + (n1 n5 - n2 n4) n6 */
static X det3(const float *n)
{
	X a = fmul_m(fmul_m(LD(n[8]), &n[4]) - fmul_m(LD(n[7]), &n[5]), &n[0]);
	X b = fmul_m(fmul_m(LD(n[1]), &n[8]) - fmul_m(LD(n[2]), &n[7]), &n[3]);
	X c = fmul_m(fmul_m(LD(n[1]), &n[5]) - fmul_m(LD(n[2]), &n[4]), &n[6]);
	return (a - b) + c;
}

/* 0x47d690 Mat4_determinant(m): expansion along the first row; the running sum is a float */
X (Mat4_determinant)(const float *m)
{
	float sum = 0.0f, sign = 1.0f, n[9];
	for (int c = 0; c < 4; c++) {
		Mat4_minor(m, n, 0, c);
		sum = (float)fadd_m(fmul_m(fmul_m(det3(n), &m[c]), &sign), &sum);
		sign = (float)fmul_m(LD(sign), (const float *)ADDR(k_m1f));         /* -1 */
	}
	return sum;
}

/* 0x47d740 Mat4_invert(out, m): out = adjugate / determinant; returns 0 (out untouched) if |det| < the double at
   k_1em8 or det is NaN (fcomp/test ah,1). Each entry is det3 * sign (fimul) / det rounded to float (fst) */
int (Mat4_invert)(float *out, const float *m)
{
	X det = Mat4_determinant(m);
	float detf = (float)det, n[9];
	X mag = det < 0 ? -det : det;
	if (!(mag >= k_1em8))
		return 0;
	for (int r = 0; r < 4; r++)
		for (int c = 0; c < 4; c++) {
			Mat4_minor(m, n, r, c);
			int sign = ((r + c) & 1) ? -1 : 1;
			out[c * 4 + r] = (float)fdiv_m(det3(n) * sign, &detf);
		}
	return 1;
}

/* 0x47d9d0 math_segmentSphere(p0, p1, dir, centre, radius, hitPoint, hitT): ray p0 + t*dir (dir unit) against a
   sphere, for a segment ending at p1; returns 1 and the entry point. Follows the original's x87 code: the
   difference vectors, the projection and r^2 are stored as floats, x of (ctr - p1) is also reused unrounded, the
   hit offsets for x and y are rounded before adding p0 (z is not); the compares keep its NaN behaviour (a NaN dot
   product skips the length test, a NaN length or distance does not reject) */
int (math_segmentSphere)(const float *p0, const float *p1, const float *dir, const float *ctr, float radius, float *hit,
                         float *t_out)
{
	const float *K0 = (const float *)ADDR(k_0f);                          /* 0.0 */
	float ax = (float)fsub_m(LD(ctr[0]), &p0[0]), ay = (float)fsub_m(LD(ctr[1]), &p0[1]);
	float az = (float)fsub_m(LD(ctr[2]), &p0[2]);
	float proj = (float)((fmul_m(LD(ay), &dir[1]) + fmul_m(LD(ax), &dir[0])) + fmul_m(LD(az), &dir[2]));
	X bx_x = fsub_m(LD(ctr[0]), &p1[0]);
	float bx = (float)bx_x, by = (float)fsub_m(LD(ctr[1]), &p1[1]), bz = (float)fsub_m(LD(ctr[2]), &p1[2]);
	float r2 = (float)fmul_m(LD(radius), &radius);
	if (!(proj > *K0))
		return 0;
	X dot_b = (fmul_m(LD(by), &dir[1]) + fmul_m(bx_x, &dir[0])) + fmul_m(LD(bz), &dir[2]);
	if (dot_b >= *K0) {
		X len_b = (fmul_m(LD(bz), &bz) + fmul_m(LD(by), &by)) + fmul_m(LD(bx), &bx);
		if (len_b >= r2)
			return 0;
	}
	X d2 = ((fmul_m(LD(az), &az) + fmul_m(LD(ay), &ay)) + fmul_m(LD(ax), &ax)) - fmul_m(LD(proj), &proj);
	if (d2 >= r2)
		return 0;
	X t = fsubr_m(x87_fsqrt(fsubr_m(d2, &r2)), &proj);
	*t_out = (float)t;
	float hx = (float)fmul_m(t, &dir[0]), hy = (float)fmul_m(t, &dir[1]);
	X tz = fmul_m(t, &dir[2]);
	float h0 = (float)fadd_m(LD(hx), &p0[0]), h1 = (float)fadd_m(LD(hy), &p0[1]), h2 = (float)fadd_m(tz, &p0[2]);
	hit[0] = h0; hit[1] = h1; hit[2] = h2;
	return 1;
}

/* 0x46e050 color_hsvToRgb(hue 0..360, sat, val, r, g, b); a sector outside 0..5 leaves the outputs unchanged */
void (color_hsvToRgb)(float hue, float sat, float val, float *r, float *g, float *b)
{
	if (!(sat >= 1e-8f)) { volatile X t = val; *r = (float)t; *g = (float)t; *b = (float)t; return; }   /* fld/fstp */
	if (!(hue < 360.0f) && !(hue > 360.0f)) hue = 0.0f;   /* fcomp + test ah,0x40: equal OR unordered (NaN -> 0) */
	X h6 = (X)hue * 0.016666668f;
	int i = ftol(h6);
	X f = h6 - i;
	float p = (float)((1.0f - (X)sat) * val);
	float q = (float)((1.0L - f * sat) * val);
	float t = (float)((1.0L - (1.0L - f) * sat) * val);
	switch (i) {
	case 0: *r = val; *g = t; *b = p; break;
	case 1: *r = q; *g = val; *b = p; break;
	case 2: *r = p; *g = val; *b = t; break;
	case 3: *r = p; *g = q; *b = val; break;
	case 4: *r = t; *g = p; *b = val; break;
	case 5: *r = val; *g = p; *b = q; break;
	}
}

/* 0x4326f0: the level (1 .. 20) a points total reaches, thresholds 100 .. 1200000: an actor's grade from its score
   (the local team's, on each kill award), the Ladder level from exp (ladder_checkAndSendRecord, lobby records) and
   the starting level (match_setupOrStartRound). The original returns the full EAX */
int (level_fromPoints)(int v)
{
	static const int limit[] = { 100, 350, 850, 1700, 3200, 5800, 10000, 16000, 25000, 40000, 60000, 90000,
	                             135000, 200000, 300000, 440000, 650000, 950000, 1200000 };
	int lvl = 1;
	for (int i = 0; i < (int)(sizeof limit / sizeof limit[0]); i++, lvl++)
		if (v < limit[i]) return lvl;
	return lvl;
}

/* 0x41f0e0 Color4_set(c, r, g, b, a): r, g, b, a copied as bits, in the
   original's store order g, b, r, a (the original moves r through the FPU, fld / fstp, which would make a signalling
   NaN quiet; here it is copied as it is) */
void (Color4_set)(u32 *c, u32 r, u32 g, u32 b, u32 a) { c[1] = g; c[2] = b; c[0] = r; c[3] = a; }
/* 0x42eeb0 rect_set(left, top, right, bottom, out): a button / hit rectangle's four corners stored */
void (rect_set)(u32 left, u32 top, u32 right, u32 bottom, u32 *out) { out[0] = left; out[1] = top; out[2] = right; out[3] = bottom; }

/* 0x480400 the length of a Vec3, returned unrounded in ST0 */
X THISCALL (Vec3_length)(const float *v)
{
	X x = v[0], y = v[1], z = v[2];
	return x87_fsqrt(x * x + y * y + z * z);
}
